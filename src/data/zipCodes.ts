export function normalizeZip(input: string): string | null {
  const digits = input.replace(/\D/g, "");
  if (digits.length >= 5) return digits.slice(0, 5);
  return null;
}

export function citySlugForZip(zip: string): string | undefined {
  const normalized = normalizeZip(zip);
  if (!normalized) return undefined;
  if (ZIP_TO_CITY_SLUG[normalized]) return ZIP_TO_CITY_SLUG[normalized];
  return ZIP3_TO_CITY_SLUG[normalized.slice(0, 3)];
}
